//! A clause may apply a proposition generic over types at closed types:
//! `ensures same_count::<u64>(a, b)` for
//! `proposition same_count<T>(a: Tagged<T>, b: Tagged<T>) = ...`.
//!
//! generics.md, "Closed applications and canonical identity": substitution
//! is declaration-identity based throughout bodies, contracts, field types,
//! and nested applications. Like a machine, the application selects one
//! proposition, `same_count` with `u64` in place of `T`, generated once per
//! application and shared by every clause that applies it; the clause then
//! names that proposition and no binder. The calls the copied formula holds
//! (`count::<T>(a)`, now `count::<u64>(a)`) are served like any other call
//! site of the machine whose clause applied it.
//!
//! Served today: type binders given plain named types, on a proposition
//! declared as one boolean formula. Any other binder or argument, and a
//! proposition defined by applying another, is unserved and refused on the
//! machine whose clause applies it.

use crate::source_state::TypedTrees;
use crate::source_state::domain::ProofFact;
use crate::source_state::expression::ExpressionHandle;
use crate::source_state::name::Identifier;
use crate::source_state::proposition::{
    PropositionApplication, PropositionBinderArgumentKind, PropositionBinderKind, PropositionBody,
    PropositionFormula,
};
use source_text::SourceSpan;
use symbols::{SymbolHandle, SymbolKind};
use typed_trees::static_operand_binding::{Served, Stop, unserved};

/// Each proposition generated so far: the generic declaration, the symbol
/// of each type it was applied at, and the proposition it selects.
#[derive(Default)]
pub(super) struct GeneratedPropositions {
    made: Vec<(SymbolHandle, Vec<SymbolHandle>, SymbolHandle)>,
}

/// Points each closed application of a generic proposition in the contracts
/// of the machine at `position` at the proposition it selects. Returns the
/// formula of each proposition generated here, whose calls the caller
/// serves as sites of that machine.
pub(super) fn close(
    program: &mut TypedTrees,
    position: usize,
    generated: &mut GeneratedPropositions,
) -> Result<Vec<ExpressionHandle>, (Stop, SourceSpan)> {
    let machine = &program.machines()[position];
    let mut facts = Vec::new();
    for state in program.machine_states(machine) {
        for contract in program
            .machine_contracts(machine)
            .iter()
            .chain(program.state_contracts(state))
        {
            facts.extend(contract.facts.handles());
        }
    }
    let mut formulas = Vec::new();
    for handle in facts {
        let ProofFact::Proposition(application) = program.proof_facts.get(handle) else {
            continue;
        };
        if application.binder_arguments.is_empty() {
            continue;
        }
        let application = application.clone();
        let span = program.proof_fact_source_span(handle).unwrap_or_default();
        let (instance, formula) =
            select(program, &application, generated).map_err(|stop| (stop, span))?;
        formulas.extend(formula);
        if let ProofFact::Proposition(application) = program.proof_facts.get_mut(handle) {
            application.proposition = instance;
            application.binder_arguments = Box::default();
        }
    }
    Ok(formulas)
}

/// The proposition `application` selects, and its formula when it is
/// generated by this call.
fn select(
    program: &mut TypedTrees,
    application: &PropositionApplication,
    generated: &mut GeneratedPropositions,
) -> Served<(SymbolHandle, Option<ExpressionHandle>)> {
    let definition = program
        .proposition_definition_by_symbol(application.proposition)
        .cloned()
        .ok_or(unserved(
            "a generic proposition applied through a parameter has no declaration to copy",
        ))?;
    let binders = program.proposition_binders(&definition).to_vec();
    if binders.len() != application.binder_arguments.len() {
        return Err(Stop::Defect(
            "a proposition application lost its binder arguments",
        ));
    }
    let mut actuals = Vec::with_capacity(binders.len());
    let mut substitutions = Vec::with_capacity(binders.len());
    for (binder, argument) in binders.iter().zip(&application.binder_arguments) {
        if binder.kind != PropositionBinderKind::Type
            || argument.kind != PropositionBinderArgumentKind::Type
            || argument.evidence_projection.is_some()
        {
            return Err(unserved(
                "a proposition applied at a binder other than a type",
            ));
        }
        let actual = program
            .type_reference_table
            .find_named_type_reference(argument.symbol)
            .filter(|_| argument.symbol.is_valid())
            .ok_or(unserved(
                "a generic proposition applied at a type that is not a closed named type",
            ))?;
        actuals.push(argument.symbol);
        substitutions.push((binder.symbol, actual));
    }
    if let Some((_, _, instance)) = generated
        .made
        .iter()
        .find(|(template, at, _)| *template == definition.symbol && *at == actuals)
    {
        return Ok((*instance, None));
    }
    if !matches!(
        definition.body,
        PropositionBody::Transparent {
            proposition: PropositionFormula::BooleanExpression(_)
        }
    ) {
        return Err(unserved(
            "a generic proposition applied at closed types must be declared as one boolean formula",
        ));
    }
    let spelled = binders
        .iter()
        .zip(&application.binder_arguments)
        .map(|(_, argument)| {
            argument
                .path
                .iter()
                .map(Identifier::as_str)
                .collect::<Vec<_>>()
                .join("::")
        })
        .collect::<Vec<_>>()
        .join("$");
    let name = format!(
        "{}$specialized${spelled}${}",
        definition.name.as_str(),
        program.symbols.symbols().len() + 1
    );
    let instance = program.symbols.insert_generated_root_from(
        definition.symbol,
        SymbolKind::Proposition,
        &name,
    );
    let copied = program
        .copy_proposition_application(
            &definition,
            instance,
            Identifier::generated(name),
            &substitutions,
        )
        .map_err(unserved)?;
    let PropositionBody::Transparent {
        proposition: PropositionFormula::BooleanExpression(formula),
    } = copied.body
    else {
        return Err(Stop::Defect("a copied proposition lost its formula"));
    };
    program.push_proposition(copied);
    generated.made.push((definition.symbol, actuals, instance));
    Ok((instance, Some(formula)))
}
