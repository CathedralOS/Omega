//! Captured source records and inert declaration anchors supplied to settlement.
//! These values grant neither lookup nor semantic acceptance.
#![forbid(unsafe_code)]
use source_provenance::PackageKeyIdentity;
use source_text::{SourceId, SourceSpan, Span};
use std::path::PathBuf;
use std::sync::Arc;
use symbols::SymbolKind;

pub use source_files::{LoadedSource, LoadedSources, SourceOrigin, directory_namespace};

#[derive(Debug, Clone, Copy, Default, PartialEq, Eq, record_storage::Record)]
pub enum SourceResolutionStratum {
    #[default]
    Base,
    CurrentActivationExtension, // Generated by the activation this compilation itself admitted.
    DependencyActivationExtension, // Generated by a dependency's already-reviewed activation.
}

use source_provenance::DependencyScope;

#[derive(Debug, Clone, PartialEq, Eq, record_storage::Record)]
pub struct SourceFile {
    pub source_id: SourceId,
    pub path: PathBuf,
    pub package_root: PathBuf, // Canonical package directory selected by the frontend.
    pub package_identity: Option<PackageKeyIdentity>, // Reconciled package identity when admitted by a package graph.
    pub dependency_scope: DependencyScope, // Dependency context (`Product` vs `Build`) this instance was checked under.
    pub origin: SourceOrigin,
    pub resolution_stratum: SourceResolutionStratum,
    pub source: Arc<str>,
}

impl SourceFile {
    pub fn directory_namespace(&self) -> Result<Vec<&str>, String> {
        directory_namespace(&self.path, &self.package_root)
    }

    pub fn source_span(&self, span: Span) -> SourceSpan {
        SourceSpan::new(self.source_id, span)
    }

    pub fn text_at(&self, span: Span) -> &str {
        self.source.get(span.start..span.end).unwrap_or("")
    }
}

#[derive(Debug)]
pub struct SourceContents {
    pub path: PathBuf,
    pub source: Arc<str>,
    pub scope: DependencyScope,
}

#[derive(Debug, Clone, PartialEq, Eq)]
pub struct RetainedDeclaration {
    source: SourceFile,
    span: Span,
    kind: SymbolKind,
}

impl RetainedDeclaration {
    /// Keep one source occurrence without accepting it or authorizing a lookup.
    pub fn from_source_occurrence(source: SourceFile, span: Span, kind: SymbolKind) -> Self {
        Self { source, span, kind }
    }

    /*
        Recover an inert declaration anchor from retained source custody.
        This establishes only a well-formed coordinate. The receiving compiler
        must still admit the source and rejoin its checked declaration.
    */
    pub fn from_retained_parts(
        mut source: SourceFile,
        span: Span,
        kind: SymbolKind,
    ) -> Result<Self, &'static str> {
        if span.start >= span.end || source.source.get(span.start..span.end).is_none() {
            return Err("retained declaration has an invalid authored source coordinate");
        }
        source.source_id = source_text::SourceId(0);
        Ok(Self { source, span, kind })
    }

    /* The immutable source custody captured when this declaration was selected. */
    pub fn source(&self) -> &SourceFile {
        &self.source
    }

    /* The original declaration anchor, independent of any later source number. */
    pub const fn span(&self) -> Span {
        self.span
    }

    /* The declaration role retained beside its source anchor. */
    pub const fn kind(&self) -> SymbolKind {
        self.kind
    }
}

pub mod source_identity {
    use crate::{SourceFile, SourceOrigin};
    use source_provenance::{
        ConsumedSourceUnit, ConsumedSourceUnitKind, canonical_consumed_unit_bytes,
        source_content_digest, toolchain_source_revision_digest,
    };
    use std::path::{Component, Path};

    pub const BUILD_PRELUDE_ROOT: &str = "<build-prelude>";

    /// Exact virtual source coordinates generated by the compiler for its Build vocabulary.
    pub fn is_build_prelude_path(path: &Path) -> bool {
        let Ok(relative) = path.strip_prefix(BUILD_PRELUDE_ROOT) else {
            return false;
        };
        let mut parts = relative.components();
        match parts.next() {
            None => true,
            Some(Component::Normal(namespace)) => {
                namespace.to_str().is_some_and(|name| {
                    name.bytes().all(|byte| byte.is_ascii_alphanumeric() || byte == b'_')
                }) && parts.as_path() == Path::new("mod.omg")
            }
            _ => false,
        }
    }

    pub fn consumed_source_unit(
        source: &SourceFile,
        generated: bool,
    ) -> Result<ConsumedSourceUnit, String> {
        let (kind, package, toolchain_namespace, relative_path) = match source.origin {
            SourceOrigin::User => {
                let package = source.package_identity.ok_or_else(|| {
                    format!(
                        "package-aware source `{}` has no reconciled package identity",
                        source.path.display()
                    )
                })?;
                let relative = source
                    .path
                    .strip_prefix(&source.package_root)
                    .map_err(|_| {
                        format!(
                            "package-aware source `{}` is outside its reconciled root `{}`",
                            source.path.display(),
                            source.package_root.display()
                        )
                    })?;
                (
                    if generated {
                        ConsumedSourceUnitKind::PackageGenerated(source.dependency_scope)
                    } else {
                        ConsumedSourceUnitKind::PackageAuthored
                    },
                    Some(package),
                    None,
                    canonical_path_components(relative, &source.path)?,
                )
            }
            origin if origin.is_toolchain() && generated => {
                return Err(format!(
                    "generated-source custody cannot name toolchain source `{}`",
                    source.path.display()
                ));
            }
            SourceOrigin::Toolchain if is_virtual_toolchain_path(&source.path) => (
                ConsumedSourceUnitKind::ToolchainVirtual,
                None,
                None,
                canonical_path_components(&source.path, &source.path)?,
            ),
            SourceOrigin::ToolchainContract if is_virtual_toolchain_path(&source.path) => {
                return Err("closed toolchain contracts require an owned source path".into());
            }
            SourceOrigin::Toolchain | SourceOrigin::ToolchainContract => {
                let namespace = source
                    .package_root
                    .file_name()
                    .and_then(|name| name.to_str())
                    .ok_or_else(|| {
                        format!(
                            "toolchain source root `{}` has no canonical UTF-8 namespace",
                            source.package_root.display()
                        )
                    })?;
                let relative = source
                    .path
                    .strip_prefix(&source.package_root)
                    .map_err(|_| {
                        format!(
                            "toolchain source `{}` is outside its canonical root `{}`",
                            source.path.display(),
                            source.package_root.display()
                        )
                    })?;
                (
                    if source.origin == SourceOrigin::ToolchainContract {
                        ConsumedSourceUnitKind::ToolchainContract
                    } else {
                        ConsumedSourceUnitKind::ToolchainOwned
                    },
                    None,
                    Some(namespace.to_owned()),
                    canonical_path_components(relative, &source.path)?,
                )
            }
        };
        let byte_count = u64::try_from(source.source.len()).map_err(|_| {
            format!(
                "compiler-consumed source `{}` byte length exceeds the canonical range",
                source.path.display()
            )
        })?;
        ConsumedSourceUnit::from_retained(
            kind,
            package,
            toolchain_namespace,
            relative_path,
            byte_count,
            source_content_digest(source.source.as_bytes()),
        )
        .map_err(str::to_owned)
    }

    pub fn canonical_path_components(
        relative: &Path,
        diagnostic_path: &Path,
    ) -> Result<Vec<String>, String> {
        let components = relative.components().collect::<Vec<_>>();
        if components.is_empty() {
            return Err(format!(
                "compiler-consumed source `{}` has an empty canonical path",
                diagnostic_path.display()
            ));
        }
        components
            .into_iter()
            .map(|component| {
                let Component::Normal(component) = component else {
                    return Err(format!(
                        "compiler-consumed source `{}` has a non-canonical relative path",
                        diagnostic_path.display()
                    ));
                };
                component.to_str().map(str::to_owned).ok_or_else(|| {
                    format!(
                        "compiler-consumed source `{}` has a non-UTF-8 path component",
                        diagnostic_path.display()
                    )
                })
            })
            .collect()
    }

    #[doc(hidden)]
    pub fn toolchain_source_identities<'source>(
        sources: impl IntoIterator<Item = &'source SourceFile>,
    ) -> Result<Vec<(crate::SourceId, [u8; 32])>, String> {
        let mut identities = sources
            .into_iter()
            .filter(|source| source.origin.is_toolchain())
            .map(|source| Ok((source.source_id, toolchain_source_identity_digest(source)?)))
            .collect::<Result<Vec<_>, String>>()?;
        identities.sort_by_key(|(source_id, _)| source_id.0);
        Ok(identities)
    }

    #[doc(hidden)]
    pub fn toolchain_source_identity_digest(source: &SourceFile) -> Result<[u8; 32], String> {
        if !source.origin.is_toolchain() {
            return Err(format!(
                "toolchain source identity requested for non-toolchain source `{}`",
                source.path.display(),
            ));
        }
        let custody_entry = canonical_source_entry(source)?;
        Ok(toolchain_source_revision_digest(&custody_entry))
    }

    pub fn canonical_source_entry(source: &SourceFile) -> Result<Vec<u8>, String> {
        Ok(canonical_consumed_unit_bytes(&consumed_source_unit(
            source, false,
        )?))
    }

    fn is_virtual_toolchain_path(path: &Path) -> bool {
        if is_build_prelude_path(path) {
            return true;
        }
        let mut components = path.components();
        let Some(Component::Normal(component)) = components.next() else {
            return false;
        };
        components.next().is_none()
            && component
                .to_str()
                .is_some_and(|component| component.starts_with('<') && component.ends_with('>'))
    }
}
