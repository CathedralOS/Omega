//! Generate the ordinary-Omega Unicode XID tables used by the hosted lexer.
//!
//! This producer is untrusted construction tooling. The product checkpoint
//! commits its output, pins this source plus unicode-ident's crate checksum and
//! Unicode version, and exhaustively checks the resulting classifier.

use std::fmt::Write as _;

fn ranges(mut predicate: impl FnMut(char) -> bool) -> Vec<(u32, u32)> {
    let mut output = Vec::new();
    let mut open = None;
    let mut previous = 0;

    for scalar in 0..=0x10ffff {
        let present = char::from_u32(scalar).is_some_and(&mut predicate);
        match (open, present) {
            (None, true) => open = Some(scalar),
            (Some(_), true) => previous = scalar,
            (Some(first), false) => {
                output.push((first, previous.max(first)));
                open = None;
            }
            (None, false) => {}
        }
    }
    if let Some(first) = open {
        output.push((first, previous.max(first)));
    }
    output
}

fn emit_array(output: &mut String, field: &str, ranges: &[(u32, u32)]) {
    writeln!(output, "    self.{field} = [").unwrap();
    for (index, (first, last)) in ranges.iter().copied().enumerate() {
        let separator = if index + 1 == ranges.len() { "" } else { "," };
        writeln!(
            output,
            "        UnicodeRange {{ first: {first}, last: {last} }}{separator}"
        )
        .unwrap();
    }
    writeln!(output, "    ];").unwrap();
}

fn main() {
    let start = ranges(unicode_ident::is_xid_start);
    let continuation = ranges(unicode_ident::is_xid_continue);
    let (major, minor, patch) = unicode_ident::UNICODE_VERSION;

    let mut output = String::new();
    writeln!(
        output,
        "// @generated by generate_omega_unicode.rs; do not hand-edit."
    )
    .unwrap();
    writeln!(
        output,
        "// Unicode {major}.{minor}.{patch}; unicode-ident 1.0.24."
    )
    .unwrap();
    writeln!(
        output,
        "// XID_Start ranges: {}; XID_Continue ranges: {}.",
        start.len(),
        continuation.len()
    )
    .unwrap();
    writeln!(output).unwrap();
    writeln!(output, "data UnicodeRange [copy] {{").unwrap();
    writeln!(output, "    first: u32 in Trapping;").unwrap();
    writeln!(output, "    last: u32 in Trapping;").unwrap();
    writeln!(output, "}}").unwrap();
    writeln!(output).unwrap();
    writeln!(output, "data UnicodeTables {{").unwrap();
    writeln!(
        output,
        "    xid_start: [UnicodeRange; {}] in Trapping;",
        start.len()
    )
    .unwrap();
    writeln!(
        output,
        "    xid_continue: [UnicodeRange; {}] in Trapping;",
        continuation.len()
    )
    .unwrap();
    writeln!(output, "    last_result: bool;").unwrap();
    writeln!(output, "}}").unwrap();
    writeln!(output).unwrap();
    writeln!(output, "machine UnicodeTables::initialize(&mut self) {{").unwrap();
    emit_array(&mut output, "xid_start", &start);
    emit_array(&mut output, "xid_continue", &continuation);
    writeln!(output, "}}").unwrap();
    writeln!(output).unwrap();
    writeln!(
        output,
        "machine UnicodeTables::is_xid_start(&mut self, scalar: u32 in Trapping) {{"
    )
    .unwrap();
    writeln!(output, "    self.last_result = false;").unwrap();
    writeln!(output, "    transition {{ _ -> scan(0) }}").unwrap();
    writeln!(
        output,
        "    state scan(&mut self, index: u32 in Trapping) {{"
    )
    .unwrap();
    writeln!(
        output,
        "        transition index < {} {{ true -> check(index) _ -> absent() }}",
        start.len()
    )
    .unwrap();
    writeln!(output, "    }}").unwrap();
    writeln!(
        output,
        "    state check(&mut self, index: u32 in Trapping) {{"
    )
    .unwrap();
    writeln!(output, "        transition scalar < self.xid_start[index].first {{ true -> absent() _ -> upper(index) }}").unwrap();
    writeln!(output, "    }}").unwrap();
    writeln!(
        output,
        "    state upper(&mut self, index: u32 in Trapping) {{"
    )
    .unwrap();
    writeln!(output, "        transition scalar <= self.xid_start[index].last {{ true -> present() _ -> scan(index + 1) }}").unwrap();
    writeln!(output, "    }}").unwrap();
    writeln!(
        output,
        "    state present(&mut self) {{ self.last_result = true; }}"
    )
    .unwrap();
    writeln!(
        output,
        "    state absent(&mut self) {{ self.last_result = false; }}"
    )
    .unwrap();
    writeln!(output, "}}").unwrap();
    writeln!(output).unwrap();
    writeln!(
        output,
        "machine UnicodeTables::is_xid_continue(&mut self, scalar: u32 in Trapping) {{"
    )
    .unwrap();
    writeln!(output, "    self.last_result = false;").unwrap();
    writeln!(output, "    transition {{ _ -> scan(0) }}").unwrap();
    writeln!(
        output,
        "    state scan(&mut self, index: u32 in Trapping) {{"
    )
    .unwrap();
    writeln!(
        output,
        "        transition index < {} {{ true -> check(index) _ -> absent() }}",
        continuation.len()
    )
    .unwrap();
    writeln!(output, "    }}").unwrap();
    writeln!(
        output,
        "    state check(&mut self, index: u32 in Trapping) {{"
    )
    .unwrap();
    writeln!(output, "        transition scalar < self.xid_continue[index].first {{ true -> absent() _ -> upper(index) }}").unwrap();
    writeln!(output, "    }}").unwrap();
    writeln!(
        output,
        "    state upper(&mut self, index: u32 in Trapping) {{"
    )
    .unwrap();
    writeln!(output, "        transition scalar <= self.xid_continue[index].last {{ true -> present() _ -> scan(index + 1) }}").unwrap();
    writeln!(output, "    }}").unwrap();
    writeln!(
        output,
        "    state present(&mut self) {{ self.last_result = true; }}"
    )
    .unwrap();
    writeln!(
        output,
        "    state absent(&mut self) {{ self.last_result = false; }}"
    )
    .unwrap();
    writeln!(output, "}}").unwrap();

    print!("{output}");
}
