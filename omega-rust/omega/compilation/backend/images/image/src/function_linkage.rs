//! A second, independent derivation of the object-to-image symbol
//! correspondence, so the reused handle coordinates are re-proved rather than
//! trusted.
//!
//! Recompute the public entry name and require one exact image symbol for each
//! object function: identity, name, text classification, offset, size, and kind
//! must survive placement. Source, wrapper, and private-callback identities are
//! not interchangeable; stored names alone cannot supply linkage authority.
//!
//! This is the symbol join, not the whole native custody argument. Sibling
//! final-image owners check executable-region inventory, instruction ownership,
//! relocation origins, and strong byte identities. Compact reports cannot stand
//! in for those checks. The crate root documents the still-separate footprint
//! certificate integration; successful linkage must not imply that it ran.
