//! Observe contents only after the structural operand has completed. The same
//! comparison template serves existing storage and freshly prepared views;
//! descriptor preparation remains inside its selected scalar branch.
//!
//! Both checked byte-sequence query kinds, a literal comparison and a named
//! predicate, are one operand observation: resolve the storage root and
//! observation path, evaluate the query leaf over them, then complete the
//! result with the selectors that leaf depends on. `byte_sequence_observation`
//! is that route; each entrypoint below constructs only its own leaf.
use super::{Expansion, LoweringError, QualifiedScalarType, Site, unsupported};
use crate::emission::operation_emission::LoweredScalarBinding;
use crate::emission::operation_emission::boolean::LoweredBooleanReturnExpression;
use crate::emission::operation_emission::calls::StructuralValueSource;
use crate::emission::operation_emission::expressions::{
    LoweredDirectExpression, LoweredElementPathSegment,
};
use crate::expression_preparation::bindings::ScalarBindings;
use crate::scalar_lowering::branch_states::prepared::{
    LoweredScalarBranchState, LoweredScalarBranchTerminator,
};
use crate::scalar_lowering::branch_states::structural_values::ValueRequest;
use crate::shared::checked_facts::value_facts;
use checked_trees::{
    CheckedBooleanExpression, CheckedScalarExpression, CheckedStorageRoot,
    CheckedStructuralPredicatePathSegment as Predicate, CheckedUnitStructuralArgumentPlan,
    CheckedUnitStructuralArgumentSourcePlan as Source, CheckedUnitStructuralPathSegment as Path,
};

impl Expansion<'_> {
    /// A completed operand is observed through a private shared parameter at
    /// position 0. It carries the declaration catalog like every other
    /// observation namespace: the generated byte reads select their live
    /// byte or element carrier from the descriptor's declared shape.
    fn descriptor_bindings(
        &self,
        place: semantic_vocabulary::PlaceId,
        structural_type: semantic_vocabulary::StructuralTypeId,
    ) -> ScalarBindings {
        ScalarBindings::new([])
            .with_structural_parameters(&[(
                0,
                terminal_psi::StructuralParameterDeclaration {
                    place,
                    position: 0,
                    structural_type,
                    multiplicity: terminal_psi::StructuralMultiplicity::Unrestricted,
                    access: terminal_psi::StructuralAccess::SharedBorrow,
                    qualifications: Vec::new(),
                    projected_qualifications: Vec::new(),
                    additional_input_qualifications: Vec::new(),
                },
            )])
            .with_structural_observations(self.structural_types)
    }

    /// The one byte-sequence operand observation. A completed value or
    /// computed subslice is read through its actual declared parameter;
    /// existing storage resolves its declared root
    /// and projects the observation path. `query` is the whole difference
    /// between the checked query kinds: it builds the leaf evaluated over that
    /// operand.
    #[allow(clippy::too_many_arguments)]
    fn byte_sequence_observation(
        &mut self,
        identities: &mut terminal_psi::TerminalIdentityTableBuilder,
        subject: &CheckedUnitStructuralArgumentPlan,
        input_types: &[QualifiedScalarType],
        target: usize,
        site: &Site<'_>,
        active: &mut Vec<super::Computation>,
        query: impl FnOnce(
            CheckedStorageRoot,
            Vec<Predicate>,
        ) -> Result<CheckedBooleanExpression, LoweringError>,
    ) -> Result<usize, LoweringError> {
        let mut range_slot = None;
        let mut completed_value = None;
        let private_bindings;
        let (bindings, root, path) = if let Source::StructuralExpression {
            expression,
            value_dependency,
            ..
        } = subject.source
        {
            let (request, source, source_path, structural_type, path) = if let Some(value) =
                value_dependency
            {
                let values = &value_facts(self.checked).structural_values;
                values
                    .root_for_value_home(value, expression)
                    .filter(|root| {
                        root.machine == self.machine
                            && root.state == site.state
                            && root.statement_ordinal == site.statement
                    })
                    .ok_or(LoweringError::Unsupported(
                        "byte operand has no exact completed value occurrence",
                    ))?;
                let request =
                    ValueRequest::prepare(identities, self.checked, value, self.structural_types)?;
                (
                    Some(request),
                    StructuralValueSource::Computed(value),
                    Vec::new(),
                    request.structural_type,
                    observation_path(&subject.path)?,
                )
            } else {
                // Existing saved storage keeps its checked borrowed route. It
                // does not rediscover or execute a value from an expression.
                let (_, state) =
                    crate::shared::declarations::state_declaration(self.checked, site.state)?;
                let source = site.bindings.shared_structural_argument(
                    identities,
                    self.checked,
                    subject,
                    self.checked.state_parameters(state),
                )?;
                let structural_type = site.bindings.structural_argument_type(&source).ok_or(
                    LoweringError::Unsupported("byte operand has no published storage carrier"),
                )?;
                (
                    None,
                    StructuralValueSource::Place(source.place),
                    source
                        .path
                        .into_iter()
                        .map(LoweredElementPathSegment::Static)
                        .collect(),
                    structural_type,
                    Vec::new(),
                )
            };
            let place = super::super::place_id(super::super::allocate_dense(self.next_place)?);
            private_bindings = self.descriptor_bindings(place, structural_type);
            completed_value = Some((request, source, source_path, place, structural_type));
            (
                &private_bindings,
                CheckedStorageRoot::Parameter { index: 0 },
                path,
            )
        } else if let Some(range) = super::subslices::range(subject) {
            let slot = self
                .subslices
                .iter()
                .find(|slot| slot.expression == range.expression)
                .ok_or(LoweringError::Unsupported(
                    "byte sequence operand has no descriptor reservation",
                ))?;
            range_slot = Some(slot.clone());
            private_bindings = self.descriptor_bindings(slot.place, slot.structural_type);
            (
                &private_bindings,
                CheckedStorageRoot::Parameter { index: 0 },
                Vec::<Predicate>::new(),
            )
        } else {
            let (_, state) =
                crate::shared::declarations::state_declaration(self.checked, site.state)?;
            let root = match subject.source {
                Source::Parameter { parameter_index } => {
                    let (position, _) = self
                        .checked
                        .state_parameters(state)
                        .iter()
                        .enumerate()
                        .filter(|(_, parameter)| {
                            !parameter.relevance.is_erased()
                                && self
                                    .checked
                                    .primitive_type_reference(parameter.type_reference)
                                    .is_none()
                        })
                        .nth(parameter_index as usize)
                        .ok_or(LoweringError::Unsupported(
                            "byte sequence operand lost its source parameter",
                        ))?;
                    CheckedStorageRoot::Parameter {
                        index: u32::try_from(position).map_err(|_| {
                            LoweringError::Unsupported("byte sequence parameter overflow")
                        })?,
                    }
                }
                Source::StructuralLocal { symbol } => {
                    let (_, local) = self.checked.state_local_declaration(state, symbol).ok_or(
                        LoweringError::Unsupported("byte sequence operand lost its local"),
                    )?;
                    if validation::reference_shell(&self.checked.typed, local.type_reference)
                        .is_some()
                    {
                        CheckedStorageRoot::ViewLocal { symbol }
                    } else {
                        CheckedStorageRoot::OwnedLocal { symbol }
                    }
                }
                _ => return unsupported("byte sequence operand has no observable operand"),
            };
            let path = observation_path(&subject.path)?;
            (site.bindings, root, path)
        };
        let mut value = bindings.expression(
            identities,
            &self.checked.facts.proven_scalar_indexes,
            &CheckedScalarExpression::Boolean(Box::new(query(root, path)?)),
        )?;
        // The template asks several questions of one already evaluated operand.
        // Capture its selectors before the length guard, then carry their exact
        // SSA identities through the selected byte observations. This also keeps
        // mutable scalar fields used as selectors from being read repeatedly.
        let mut captures = OperandSelectors::new(input_types.len());
        captures.capture(&mut value);
        let mut operand_types = input_types.to_vec();
        operand_types.extend(
            captures
                .values
                .iter()
                .map(|value| QualifiedScalarType::from(value.scalar_type())),
        );
        let mut completed = self.binding(
            &operand_types,
            input_types.len(),
            target,
            LoweredScalarBinding::Expression(value),
        );
        for (ordinal, value) in captures.values.into_iter().enumerate().rev() {
            completed = self.direct_value(
                &operand_types[..input_types.len() + ordinal],
                completed,
                value,
            )?;
        }
        let entry = match range_slot {
            Some(slot) => self.subslice(
                identities,
                subject,
                &slot,
                input_types,
                completed,
                site,
                active,
            )?,
            None => completed,
        };
        let Some((request, source, path, place, structural_type)) = completed_value else {
            return Ok(entry);
        };
        // The query borrows the actual completed binding through this declared
        // parameter. A reservation alone is never storage for an observation.
        self.states[entry - self.base].structural_parameters.push(
            terminal_psi::StructuralParameterDeclaration {
                place,
                position: 0,
                structural_type,
                multiplicity: terminal_psi::StructuralMultiplicity::Unrestricted,
                access: terminal_psi::StructuralAccess::SharedBorrow,
                qualifications: Vec::new(),
                projected_qualifications: Vec::new(),
                additional_input_qualifications: Vec::new(),
            },
        );
        let entry = self.push(LoweredScalarBranchState::continuing(
            input_types.to_vec(),
            LoweredScalarBranchTerminator::Capture {
                target: entry,
                arguments: super::parameters(input_types),
                source,
                path,
                access: terminal_psi::StructuralAccess::SharedBorrow,
            },
        ));
        Ok(match request {
            Some(request) => request.finish(input_types, entry, self),
            None => entry,
        })
    }

    /// A literal equality comparison observes the operand as an extent,
    /// truncated to the declared carrier's length when it has one. Its
    /// negation is the same observation under a `Not` leaf.
    #[allow(clippy::too_many_arguments)]
    pub(super) fn byte_literal_comparison(
        &mut self,
        identities: &mut terminal_psi::TerminalIdentityTableBuilder,
        bytes: &[u8],
        maximum_length: Option<u64>,
        negated: bool,
        subject: &CheckedUnitStructuralArgumentPlan,
        input_types: &[QualifiedScalarType],
        target: usize,
        site: &Site<'_>,
        active: &mut Vec<super::Computation>,
    ) -> Result<usize, LoweringError> {
        self.byte_sequence_observation(
            identities,
            subject,
            input_types,
            target,
            site,
            active,
            |root, path| {
                let comparison = CheckedBooleanExpression::byte_literal_equality_in_extent(
                    root,
                    path,
                    bytes,
                    maximum_length,
                )
                .ok_or(LoweringError::Unsupported(
                    "byte comparison literal exceeds its index carrier",
                ))?;
                Ok(if negated {
                    CheckedBooleanExpression::Not(Box::new(comparison))
                } else {
                    comparison
                })
            },
        )
    }

    /// A declared byte predicate observes the same operand under its own named
    /// judgment.
    #[allow(clippy::too_many_arguments)]
    pub(super) fn byte_predicate(
        &mut self,
        identities: &mut terminal_psi::TerminalIdentityTableBuilder,
        predicate: terminal_psi::ByteSequencePredicate,
        subject: &CheckedUnitStructuralArgumentPlan,
        input_types: &[QualifiedScalarType],
        target: usize,
        site: &Site<'_>,
        active: &mut Vec<super::Computation>,
    ) -> Result<usize, LoweringError> {
        self.byte_sequence_observation(
            identities,
            subject,
            input_types,
            target,
            site,
            active,
            |root, path| {
                Ok(CheckedBooleanExpression::ByteSequencePredicate {
                    predicate,
                    root,
                    path,
                })
            },
        )
    }
}

/// Selectors are operands of the one content query, not independent operands
/// of the length and each byte observation generated from that query.
struct OperandSelectors {
    first_parameter: usize,
    values: Vec<LoweredDirectExpression>,
    paths: Vec<(
        Vec<LoweredElementPathSegment>,
        Vec<LoweredElementPathSegment>,
    )>,
}
impl OperandSelectors {
    fn new(first_parameter: usize) -> Self {
        Self {
            first_parameter,
            values: Vec::new(),
            paths: Vec::new(),
        }
    }
    fn bind(&mut self, value: LoweredDirectExpression) -> LoweredDirectExpression {
        let position = self.first_parameter + self.values.len();
        let scalar_type = value.scalar_type();
        self.values.push(value);
        LoweredDirectExpression::Parameter {
            position,
            scalar_type,
        }
    }
    fn capture(&mut self, expression: &mut LoweredDirectExpression) {
        match expression {
            LoweredDirectExpression::Boolean { expression } => self.boolean(expression),
            LoweredDirectExpression::ElementViewLength { path, .. }
            | LoweredDirectExpression::ByteSequenceFieldLength { path, .. }
            | LoweredDirectExpression::ByteSequenceFieldRead { path, .. } => {
                if let Some((_, prepared)) =
                    self.paths.iter().find(|(original, _)| original == path)
                {
                    *path = prepared.clone();
                    return;
                }
                let original = path.clone();
                for segment in path.iter_mut() {
                    if let LoweredElementPathSegment::RuntimeIndex {
                        selector, extent, ..
                    } = segment
                    {
                        *selector = self.bind(selector.clone());
                        *extent = extent.take().map(|value| self.bind(value));
                    }
                }
                self.paths.push((original, path.clone()));
            }
            _ => {}
        }
    }
    fn boolean(&mut self, expression: &mut LoweredBooleanReturnExpression) {
        match expression {
            LoweredBooleanReturnExpression::Not { operand } => self.boolean(operand),
            LoweredBooleanReturnExpression::And { left, right }
            | LoweredBooleanReturnExpression::Or { left, right }
            | LoweredBooleanReturnExpression::Equal { left, right } => {
                self.boolean(left);
                self.boolean(right);
            }
            LoweredBooleanReturnExpression::IntegerComparison { left, right, .. } => {
                self.capture(left);
                self.capture(right);
            }
            _ => {}
        }
    }
}

/// The completed operand's storage path as an observation path. A case
/// segment selects the payload whose field the next segment names.
fn observation_path(path: &[Path]) -> Result<Vec<Predicate>, LoweringError> {
    path.iter()
        .map(|segment| match segment {
            Path::Referent => Ok(Predicate::Referent),
            Path::Field(field) => Ok(Predicate::Field(field.clone())),
            Path::Case(case) => Ok(Predicate::Case(case.clone())),
            Path::FixedIndex(index) => Ok(Predicate::FixedIndex(*index)),
            Path::RuntimeIndex(index) => Ok(Predicate::RuntimeIndex(index.clone())),
            _ => unsupported("byte operand has no scalar observation path"),
        })
        .collect()
}
