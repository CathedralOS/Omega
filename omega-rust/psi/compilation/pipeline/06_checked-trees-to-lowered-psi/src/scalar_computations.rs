        impl super::Expansion<'_> {
            #[allow(clippy::too_many_arguments)]
            pub(crate) fn structural_field(
                &mut self,
                identities: &mut terminal_psi::TerminalIdentityTableBuilder,
                computation: checked_trees::CheckedScalarComputationHandle,
                receiver_expression: typed_trees::expression::ExpressionHandle,
                receiver: checked_trees::CheckedStructuralValueHandle,
                subject: &CheckedUnitStructuralArgumentPlan,
                field: symbols::SymbolHandle,
                atomic_ordering: Option<terminal_psi::MemoryOrdering>,
                scalar_type: ScalarType,
                normal_cleanup_actions: arena::HandleSpan<
                    checked_trees::CheckedNormalCleanupAction,
                >,
                input_types: &[super::QualifiedScalarType],
                target: usize,
                site: &super::Site<'_>,
            ) -> Result<usize, LoweringError> {
                let (_, state) =
                    crate::shared::declarations::state_declaration(self.checked, site.state)?;
                let CheckedScalarComputationKind::StructuralField { result_type, .. } =
                    value_facts(self.checked)
                        .scalar_computations
                        .nodes
                        .get(computation)
                        .kind
                else {
                    return unsupported("field observation lost its complete checked result type");
                };
                let result_type = self.qualifications.value_type(self.checked, result_type)?;
                let established = self
                    .established_values
                    .iter()
                    .rev()
                    .find(|value| match value {
                        super::EstablishedValue::Produced { root, .. } => {
                            if receiver.is_valid() {
                                *root == receiver
                            } else {
                                receiver_expression.is_valid()
                                    && receiver_expression
                                        == value_facts(self.checked)
                                            .structural_values
                                            .nodes
                                            .get(*root)
                                            .expression
                            }
                        }
                        super::EstablishedValue::Copied { expression, .. } => {
                            receiver_expression.is_valid() && receiver_expression == *expression
                        }
                    })
                    .cloned();
                let produced = match &established {
                    Some(super::EstablishedValue::Produced { root, .. }) => Some(*root),
                    _ if receiver.is_valid() => Some(receiver),
                    _ => None,
                };
                if let Some(value) = produced {
                    use crate::scalar_lowering::branch_states::prepared::{
                        LoweredScalarBranchState, LoweredScalarBranchTerminator,
                        LoweredScalarEffect,
                    };
                    let target = if established.is_none() {
                        self.complete_observation_receiver(
                            normal_cleanup_actions,
                            input_types,
                            result_type,
                            target,
                        )
                    } else {
                        target
                    };
                    let mut arguments = super::parameters(input_types);
                    arguments.push(super::parameter(input_types.len(), result_type));
                    let observe = self.push(LoweredScalarBranchState {
                        structural_parameters: Vec::new(),
                        structural_effects: vec![LoweredScalarEffect::ObserveStructuralValue {
                            value,
                            observation: computation,
                        }],
                        parameter_types: input_types.to_vec(),
                        erased_formal_types: Vec::new(),
                        erased_proof_formals: Vec::new(),
                        bindings: Vec::new(),
                        terminator: LoweredScalarBranchTerminator::jump(target, arguments),
                    });
                    return match established {
                        Some(super::EstablishedValue::Produced { .. }) => Ok(observe),
                        _ => Ok((*receiver_request(self.fields, subject, field)?).finish(
                            input_types,
                            observe,
                            self,
                        )),
                    };
                }
                let mut expression = match established {
                    Some(super::EstablishedValue::Copied {
                        place,
                        structural_type,
                        source,
                        ..
                    }) => copied_observation(
                        self.fields,
                        site.bindings,
                        self.structural_types,
                        subject,
                        field,
                        scalar_type,
                        terminal_psi::StructuralArgument::whole(
                            place,
                            terminal_psi::StructuralAccess::SharedBorrow,
                        ),
                        structural_type,
                        &source,
                        atomic_ordering,
                    )?,
                    Some(super::EstablishedValue::Produced { .. }) => {
                        return unsupported("produced observation lost its value dependency");
                    }
                    None => {
                        let binding = field_binding(self.fields, subject, field, scalar_type)?;
                        let home = observation_source(
                            identities,
                            self.checked,
                            binding,
                            site.bindings,
                            self.checked.state_parameters(state),
                            subject,
                        )?;
                        observe(binding, site.bindings, home, None, atomic_ordering)?
                    }
                };
                expression.retain_observed_type(result_type, input_types)?;
                let mut arguments = super::parameters(input_types);
                arguments.push(super::parameter(input_types.len(), result_type));
                let observation = self.push(crate::scalar_lowering::branch_states::prepared::LoweredScalarBranchState {
                    structural_parameters: Vec::new(),
                    structural_effects: Vec::new(),
                    parameter_types: input_types.to_vec(),
                    erased_formal_types: Vec::new(),
                    erased_proof_formals: Vec::new(),
                    bindings: vec![crate::emission::operation_emission::LoweredScalarBinding::Expression(expression)],
                    terminator: crate::scalar_lowering::branch_states::prepared::LoweredScalarBranchTerminator::jump(target, arguments),
                });
                Ok(observation)
            }
        }

