use std::collections::BTreeMap;
use std::path::PathBuf;
use std::sync::Arc;

use crate::{
    DependencyScope, SourceFile, SourceId, SourceOrigin, SourceResolutionStratum, SourceSpan,
};
use semantic_vocabulary::PackageKeyIdentity;

#[derive(Debug, Clone, Default, PartialEq, Eq)]
pub struct SourceMap {
    files: Vec<SourceFile>,
    selection: SourceSelection,
    /// Authorized product-scope dependency edges by requesting package:
    /// requester identity, then `alias -> target` identity. Only
    /// `DependencyPurpose::Product` edges may enter this roster; build-scope
    /// edges are compilation-local nameability and never become product
    /// selection authority
    /// (wiki/spec/build/scoped_execution.md, "Selecting product declarations
    /// without executing them").
    product_dependencies: BTreeMap<PackageKeyIdentity, BTreeMap<String, PackageKeyIdentity>>,
}

/// Backing coordinates survive across requests; activation does not. Ordinary
/// source maps select every appended file. A lineage fork selects only files
/// admitted again for that compilation, without deleting historical payloads.
#[derive(Debug, Clone, Default, PartialEq, Eq)]
enum SourceSelection {
    #[default]
    All,
    Explicit(Vec<bool>),
}

/// Invocation-owned coordinates for sealed source instances. The catalogue
/// retains bytes and custody, never active imports or dependency authority.
/// Requests borrow it only while admitting a source frontier; their maps remain
/// immutable snapshots once passed to the language pipeline.
#[derive(Debug, Default)]
pub struct SourceCatalogue {
    backing: SourceMap,
}

impl SourceCatalogue {
    pub fn begin_selection(&self) -> SourceMap {
        SourceMap {
            files: self.backing.files.clone(),
            selection: SourceSelection::Explicit(vec![false; self.backing.files.len()]),
            product_dependencies: BTreeMap::new(),
        }
    }

    /// Join the exact coordinate prefix, then select an admitted instance.
    /// Delayed current-activation outputs always append: an earlier activation's
    /// identical generated bytes cannot become this activation's old prefix.
    pub fn admit_checked_instance<'selection>(
        &mut self,
        selection: &'selection mut SourceMap,
        path: PathBuf,
        source: impl Into<Arc<str>>,
        package_root: PathBuf,
        package_identity: Option<PackageKeyIdentity>,
        origin: SourceOrigin,
        resolution_stratum: SourceResolutionStratum,
        dependency_scope: DependencyScope,
    ) -> Result<&'selection SourceFile, String> {
        if origin == SourceOrigin::User && package_identity.is_none() {
            return Err(format!(
                "cannot catalogue source {} before its package owner is sealed",
                path.display()
            ));
        }
        if !self.backing.retains_source_storage(selection) {
            return Err(
                "source selection does not belong to this catalogue's coordinate prefix".into(),
            );
        }
        let admitted = if resolution_stratum == SourceResolutionStratum::CurrentActivationExtension
        {
            self.backing.add_checked_instance(
                path,
                source,
                package_root,
                package_identity,
                origin,
                resolution_stratum,
                dependency_scope,
            )
        } else {
            self.backing.select_checked_instance(
                path,
                source,
                package_root,
                package_identity,
                origin,
                resolution_stratum,
                dependency_scope,
            )
        }
        .source_id;
        let previous_length = selection.files.len();
        if matches!(selection.selection, SourceSelection::All) {
            selection.selection = SourceSelection::Explicit(vec![true; previous_length]);
        }
        selection
            .files
            .extend_from_slice(&self.backing.files[previous_length..]);
        if let SourceSelection::Explicit(selected) = &mut selection.selection {
            selected.resize(self.backing.files.len(), false);
            selected[admitted.0] = true;
        }
        Ok(&selection.files[admitted.0])
    }
}

impl SourceSelection {
    fn includes(&self, source: SourceId) -> bool {
        match self {
            Self::All => true,
            Self::Explicit(selected) => selected.get(source.0).copied().unwrap_or(false),
        }
    }
}

impl SourceMap {
    pub fn from_files(files: Vec<SourceFile>) -> Self {
        Self {
            files,
            selection: SourceSelection::All,
            product_dependencies: BTreeMap::new(),
        }
    }

    /// Retain immutable coordinates, but no active sources or dependency edges.
    /// The package owner must admit the new closure and its product edges anew.
    /// Historical maps keep their own membership and diagnostic payloads.
    pub fn fork_source_selection(&self) -> Result<Self, String> {
        if let Some(file) = self
            .files
            .iter()
            .find(|file| file.origin == SourceOrigin::User && file.package_identity.is_none())
        {
            return Err(format!(
                "cannot retain source coordinates for {} before its package owner is sealed",
                file.path.display()
            ));
        }
        Ok(Self {
            files: self.files.clone(),
            selection: SourceSelection::Explicit(vec![false; self.files.len()]),
            product_dependencies: BTreeMap::new(),
        })
    }

    /// Current activation membership, independent of retained payload lookup.
    pub fn source_is_selected(&self, source: SourceId) -> bool {
        source.0 < self.files.len() && self.selection.includes(source)
    }

    /// Coordinate preservation compares backing, not current activation.
    pub fn retains_source_storage(&self, predecessor: &Self) -> bool {
        self.files.starts_with(&predecessor.files)
    }

    /// Reuse coordinates only for the exact bytes and checked source custody.
    /// A changed owner, scope, origin or activation stratum is a new record;
    /// activating an existing record never rewrites historical metadata.
    pub fn select_checked_instance(
        &mut self,
        path: PathBuf,
        source: impl Into<Arc<str>>,
        package_root: PathBuf,
        package_identity: Option<PackageKeyIdentity>,
        origin: SourceOrigin,
        resolution_stratum: SourceResolutionStratum,
        dependency_scope: DependencyScope,
    ) -> &SourceFile {
        let source = source.into();
        let retained = self.files.iter().position(|file| {
            file.path == path
                && file.source == source
                && file.package_root == package_root
                && file.package_identity == package_identity
                && file.origin == origin
                && file.resolution_stratum == resolution_stratum
                && file.dependency_scope == dependency_scope
        });
        if let Some(position) = retained {
            if let SourceSelection::Explicit(selected) = &mut self.selection {
                selected[position] = true;
            }
            return &self.files[position];
        }
        self.add_checked_instance(
            path,
            source,
            package_root,
            package_identity,
            origin,
            resolution_stratum,
            dependency_scope,
        )
    }

    /// Install the completed default-build owner's metadata before resolution.
    /// Supplied package identities and toolchain declarations remain exact.
    /// Source IDs, bytes and checked-context instances are never coalesced.
    pub fn bind_default_anonymous_owner(
        &mut self,
        root: &std::path::Path,
        identity: PackageKeyIdentity,
    ) -> Result<(), String> {
        for file in self.selected_files() {
            if file.origin == SourceOrigin::User
                && file.package_identity.is_none()
                && file.package_root != root
            {
                return Err(format!(
                    "source {} has no supplied owner outside the anonymous capture",
                    file.path.display()
                ));
            }
        }
        let selection = &self.selection;
        for file in &mut self.files {
            if !selection.includes(file.source_id) {
                continue;
            }
            if file.origin == SourceOrigin::User && file.package_identity.is_none() {
                file.package_identity = Some(identity);
            }
        }
        Ok(())
    }

    /// Record product-scope dependency edges keyed by requesting package.
    /// Aliases are already exact and per-package unique upstream.
    pub fn retain_product_dependency_scope<'a>(
        &mut self,
        edges: impl IntoIterator<Item = (PackageKeyIdentity, &'a str, PackageKeyIdentity)>,
    ) {
        for (requester, alias, target) in edges {
            self.product_dependencies
                .entry(requester)
                .or_default()
                .insert(alias.to_owned(), target);
        }
    }

    /// The product-scope dependency `alias` authorizes for `requester`, or
    /// `None` when the requester holds no such product edge. A build-scope
    /// alias, an unknown spelling, and a consumer's borrowed namespace all
    /// resolve the same way here: absent.
    pub fn product_dependency_target(
        &self,
        requester: PackageKeyIdentity,
        alias: &str,
    ) -> Option<PackageKeyIdentity> {
        self.product_dependencies
            .get(&requester)?
            .get(alias)
            .copied()
    }

    pub fn add(&mut self, path: PathBuf, source: String) -> &SourceFile {
        let package_root = path
            .parent()
            .map(PathBuf::from)
            .unwrap_or_else(|| PathBuf::from("."));
        self.add_with_metadata(path, source, package_root, None, SourceOrigin::User)
    }

    pub fn add_with_metadata(
        &mut self,
        path: PathBuf,
        source: String,
        package_root: PathBuf,
        package_identity: Option<PackageKeyIdentity>,
        origin: SourceOrigin,
    ) -> &SourceFile {
        self.add_with_metadata_and_resolution_stratum(
            path,
            source,
            package_root,
            package_identity,
            origin,
            SourceResolutionStratum::Base,
        )
    }

    pub fn add_with_metadata_and_resolution_stratum(
        &mut self,
        path: PathBuf,
        source: String,
        package_root: PathBuf,
        package_identity: Option<PackageKeyIdentity>,
        origin: SourceOrigin,
        resolution_stratum: SourceResolutionStratum,
    ) -> &SourceFile {
        self.add_checked_instance(
            path,
            source,
            package_root,
            package_identity,
            origin,
            resolution_stratum,
            DependencyScope::Product,
        )
    }

    /// Add one checked instance of a source. The same path may join once per
    /// dependency scope: the two instances share source bytes and package
    /// identity but nothing else
    /// (wiki/spec/build/scoped_execution.md, "Two checked contexts").
    /// Retained parser text shares its allocation; callers constructing new
    /// text may transfer an owned string through the same boundary.
    pub fn add_checked_instance(
        &mut self,
        path: PathBuf,
        source: impl Into<Arc<str>>,
        package_root: PathBuf,
        package_identity: Option<PackageKeyIdentity>,
        origin: SourceOrigin,
        resolution_stratum: SourceResolutionStratum,
        dependency_scope: DependencyScope,
    ) -> &SourceFile {
        self.files.push(SourceFile {
            source_id: SourceId(self.files.len()),
            path,
            package_root,
            package_identity,
            dependency_scope,
            origin,
            resolution_stratum,
            source: source.into(),
        });
        if let SourceSelection::Explicit(selected) = &mut self.selection {
            selected.push(true);
        }

        self.files
            .last()
            .expect("source map should contain added file")
    }

    pub fn get(&self, source_id: SourceId) -> Option<&SourceFile> {
        self.files.get(source_id.0)
    }

    pub fn file_at(&self, source_span: SourceSpan) -> Option<&SourceFile> {
        self.get(source_span.source_id)
    }

    pub fn same_package(&self, left: SourceSpan, right: SourceSpan) -> bool {
        match (self.file_at(left), self.file_at(right)) {
            (Some(left), Some(right)) => same_package_files(left, right),
            _ => false,
        }
    }

    /// Whether two declarations belong to one checked instance of a package:
    /// the same package identity AND the same dependency scope. Two checked
    /// instances of one source are the same package but never the same
    /// checked context — lexical sharing (module namespaces, package-private
    /// visibility, per-context target selection) keys off this predicate.
    pub fn same_checked_instance(&self, left: SourceSpan, right: SourceSpan) -> bool {
        match (self.file_at(left), self.file_at(right)) {
            (Some(left), Some(right)) => {
                left.dependency_scope == right.dependency_scope
                    && match (left.package_identity, right.package_identity) {
                        (Some(left), Some(right)) => left == right,
                        (None, None) => left.package_root == right.package_root,
                        _ => false,
                    }
            }
            _ => false,
        }
    }

    /// Whether a source-backed reference may resolve a declaration under the
    /// checked-purpose and activation-local stratum boundaries.
    ///
    /// Base sources cannot observe declarations generated by the current
    /// activation. Extension sources may observe the complete retained base
    /// and every source in their extension stratum. Neither purpose may select
    /// the other's checked declarations. Designated product operands use their
    /// separate product-selection boundary, not ordinary source visibility.
    pub fn reference_can_see_declaration(
        &self,
        reference: SourceSpan,
        declaration: SourceSpan,
    ) -> bool {
        if let SourceSelection::Explicit(_) = &self.selection {
            // Inactive is not missing metadata. The source-free exception
            // below cannot grant access to a historical declaration, nor can
            // an invalid source-backed reference borrow another activation.
            if !self.source_is_selected(declaration.source_id)
                || (reference.span.start != reference.span.end
                    && !self.source_is_selected(reference.source_id))
            {
                return false;
            }
        }
        if reference.span.start == reference.span.end {
            return true;
        }
        let Some(reference) = self.file_at(reference) else {
            return true;
        };
        let Some(declaration) = self.file_at(declaration) else {
            return true;
        };
        if reference.dependency_scope != declaration.dependency_scope {
            return false;
        }
        match declaration.resolution_stratum {
            SourceResolutionStratum::Base => true,
            SourceResolutionStratum::CurrentActivationExtension => {
                reference.resolution_stratum == SourceResolutionStratum::CurrentActivationExtension
            }
            // A dependency's generated declarations are its handoff to every
            // consumer, so a reference from another package selects them like
            // any imported declaration. The dependency's own authored units
            // were admitted before its activation ran and still cannot.
            SourceResolutionStratum::DependencyActivationExtension => {
                reference.resolution_stratum != SourceResolutionStratum::Base
                    || !same_package_files(reference, declaration)
            }
        }
    }

    pub fn resolution_strata_separate(&self, left: SourceSpan, right: SourceSpan) -> bool {
        match (self.file_at(left), self.file_at(right)) {
            (Some(left), Some(right)) => left.resolution_stratum != right.resolution_stratum,
            _ => false,
        }
    }

    /// Backing-coordinate frontier for appending a new source, not an active count.
    pub fn len(&self) -> usize {
        self.files.len()
    }

    pub fn is_empty(&self) -> bool {
        self.files.is_empty()
    }

    /// Every backing source record, including inactive historical payloads,
    /// in source-id order. Current closure consumers use `selected_files`.
    /// Consumers that derive order-independent identity must sort their own
    /// canonical rows rather than treating load order as semantics.
    pub fn files(&self) -> impl Iterator<Item = &SourceFile> {
        self.files.iter()
    }

    /// Files consumed by this compilation, not the retained backing catalogue.
    pub fn selected_files(&self) -> impl Iterator<Item = &SourceFile> {
        self.files
            .iter()
            .filter(|file| self.selection.includes(file.source_id))
    }

    pub fn text_at(&self, source_span: SourceSpan) -> &str {
        self.get(source_span.source_id)
            .map(|file| file.text_at(source_span.span))
            .unwrap_or("")
    }
}

/// Reconciled package identity decides membership; the package root is the
/// fallback for sources no package graph has admitted yet.
fn same_package_files(left: &SourceFile, right: &SourceFile) -> bool {
    match (left.package_identity, right.package_identity) {
        (Some(left), Some(right)) => left == right,
        (None, None) => left.package_root == right.package_root,
        _ => false,
    }
}

