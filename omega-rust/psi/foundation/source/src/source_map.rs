    #[test]
    fn catalogue_extends_delayed_views_without_selecting_sibling_sources() {
        let owner = PackageKeyIdentity::from_digest([41; 32]).unwrap();
        let dependency = PackageKeyIdentity::from_digest([42; 32]).unwrap();
        let mut catalogue = crate::SourceCatalogue::default();
        let admit =
            |catalogue: &mut crate::SourceCatalogue, view: &mut SourceMap, path: &str, stratum| {
                catalogue
                    .admit_checked_instance(
                        view,
                        PathBuf::from(path),
                        "retained bytes",
                        PathBuf::from("package"),
                        Some(owner),
                        SourceOrigin::User,
                        stratum,
                        crate::DependencyScope::Product,
                    )
                    .unwrap()
                    .source_id
            };
        let mut first = catalogue.begin_selection();
        let authored = admit(
            &mut catalogue,
            &mut first,
            "authored.omg",
            SourceResolutionStratum::Base,
        );
        first.retain_product_dependency_scope([(owner, "dependency", dependency)]);
        let saved = first.clone();
        let mut sibling = catalogue.begin_selection();
        assert_eq!(sibling.selected_files().count(), 0);
        assert_eq!(sibling.product_dependency_target(owner, "dependency"), None);
        let sibling_source = admit(
            &mut catalogue,
            &mut sibling,
            "sibling.omg",
            SourceResolutionStratum::Base,
        );
        let generated = admit(
            &mut catalogue,
            &mut first,
            "generated.omg",
            SourceResolutionStratum::CurrentActivationExtension,
        );
        assert_eq!((authored.0, sibling_source.0, generated.0), (0, 1, 2));
        assert!(first.retains_source_storage(&saved));
        assert!(!first.source_is_selected(sibling_source));
        assert!(first.source_is_selected(authored));
        assert!(first.source_is_selected(generated));
        assert_eq!(
            first.product_dependency_target(owner, "dependency"),
            Some(dependency)
        );
        assert_eq!(saved.len(), 1);
        assert_eq!(sibling.len(), 2);
        let mut later = catalogue.begin_selection();
        assert_eq!(
            admit(
                &mut catalogue,
                &mut later,
                "authored.omg",
                SourceResolutionStratum::Base
            ),
            authored
        );
        let regenerated = admit(
            &mut catalogue,
            &mut later,
            "generated.omg",
            SourceResolutionStratum::CurrentActivationExtension,
        );
        assert_eq!(regenerated.0, 3);
        assert!(!later.source_is_selected(generated));
        assert!(!later.source_is_selected(sibling_source));
        assert_eq!(later.selected_files().count(), 2);
    }

    #[test]
    fn catalogue_refuses_unsealed_owners_and_foreign_coordinate_prefixes() {
        let mut catalogue = crate::SourceCatalogue::default();
        let mut selection = catalogue.begin_selection();
        let refused = catalogue
            .admit_checked_instance(
                &mut selection,
                PathBuf::from("unsealed.omg"),
                "bytes",
                PathBuf::from("package"),
                None,
                SourceOrigin::User,
                SourceResolutionStratum::Base,
                crate::DependencyScope::Product,
            )
            .unwrap_err();
        assert!(refused.contains("before its package owner is sealed"));
        assert_eq!(selection.len(), 0);
        assert_eq!(catalogue.begin_selection().len(), 0);
        selection.add_with_metadata(
            PathBuf::from("foreign.omg"),
            "foreign bytes".into(),
            PathBuf::from("toolchain"),
            None,
            SourceOrigin::Toolchain,
        );
        let saved = selection.clone();
        let refused = catalogue
            .admit_checked_instance(
                &mut selection,
                PathBuf::from("current.omg"),
                "bytes",
                PathBuf::from("toolchain"),
                None,
                SourceOrigin::Toolchain,
                SourceResolutionStratum::Base,
                crate::DependencyScope::Product,
            )
            .unwrap_err();
        assert!(refused.contains("coordinate prefix"));
        assert_eq!(selection, saved);
        assert_eq!(catalogue.begin_selection().len(), 0);
    }

    #[test]
    fn selected_sources_keep_coordinates_without_inheriting_activation_or_edges() {
        let owner = PackageKeyIdentity::from_digest([5; 32]).expect("owner identity");
        let dependency = PackageKeyIdentity::from_digest([6; 32]).expect("dependency identity");
        let mut original = SourceMap::default();
        let selected = original
            .add_with_metadata(
                PathBuf::from("kit/selected.omg"),
                String::from("data Selected {}"),
                PathBuf::from("kit"),
                Some(owner),
                SourceOrigin::User,
            )
            .source_span(Span::new(5, 13));
        let sibling = original
            .add_with_metadata(
                PathBuf::from("kit/sibling.omg"),
                String::from("data Sibling {}"),
                PathBuf::from("kit"),
                Some(owner),
                SourceOrigin::User,
            )
            .source_span(Span::new(5, 12));
        original.retain_product_dependency_scope([(owner, "old", dependency)]);

        let mut current = original
            .fork_source_selection()
            .expect("sealed source owners");
        assert_eq!(current.selected_files().count(), 0);
        assert_eq!(current.files().count(), 2);
        assert!(current.get(sibling.source_id).is_some());
        assert_eq!(current.product_dependency_target(owner, "old"), None);
        assert!(!current.reference_can_see_declaration(SourceSpan::default(), sibling));

        let retained = current.select_checked_instance(
            PathBuf::from("kit/selected.omg"),
            String::from("data Selected {}"),
            PathBuf::from("kit"),
            Some(owner),
            SourceOrigin::User,
            SourceResolutionStratum::Base,
            crate::DependencyScope::Product,
        );
        assert_eq!(retained.source_id, selected.source_id);
        assert_eq!(current.selected_files().count(), 1);
        assert!(current.reference_can_see_declaration(selected, selected));
        assert!(!current.reference_can_see_declaration(selected, sibling));
        assert!(!current.reference_can_see_declaration(sibling, selected));
        assert!(!current.reference_can_see_declaration(
            SourceSpan::new(SourceId(99), Span::new(1, 2)),
            selected,
        ));
        assert!(original.source_is_selected(sibling.source_id));
        assert_eq!(
            original.product_dependency_target(owner, "old"),
            Some(dependency)
        );
        assert!(original.reference_can_see_declaration(selected, sibling));
        assert!(original.files().eq(current.files()));
    }

    #[test]
    fn source_coordinate_reuse_requires_every_checked_owner_dimension() {
        let owner = PackageKeyIdentity::from_digest([7; 32]).expect("owner identity");
        let other_owner = PackageKeyIdentity::from_digest([8; 32]).expect("other owner");
        let mut original = SourceMap::default();
        original.add_with_metadata(
            PathBuf::from("kit/module.omg"),
            String::from("data Item {}"),
            PathBuf::from("kit"),
            Some(owner),
            SourceOrigin::User,
        );
        let mut current = original
            .fork_source_selection()
            .expect("sealed source owners");
        let variations = [
            (
                "data Other {}",
                owner,
                SourceOrigin::User,
                SourceResolutionStratum::Base,
                crate::DependencyScope::Product,
            ),
            (
                "data Item {}",
                other_owner,
                SourceOrigin::User,
                SourceResolutionStratum::Base,
                crate::DependencyScope::Product,
            ),
            (
                "data Item {}",
                owner,
                SourceOrigin::Toolchain,
                SourceResolutionStratum::Base,
                crate::DependencyScope::Product,
            ),
            (
                "data Item {}",
                owner,
                SourceOrigin::User,
                SourceResolutionStratum::DependencyActivationExtension,
                crate::DependencyScope::Product,
            ),
            (
                "data Item {}",
                owner,
                SourceOrigin::User,
                SourceResolutionStratum::Base,
                crate::DependencyScope::Build,
            ),
        ];
        for (position, (text, package, origin, stratum, scope)) in
            variations.into_iter().enumerate()
        {
            let selected = current.select_checked_instance(
                PathBuf::from("kit/module.omg"),
                text.to_owned(),
                PathBuf::from("kit"),
                Some(package),
                origin,
                stratum,
                scope,
            );
            assert_eq!(selected.source_id, SourceId(position + 1));
        }
        assert!(!current.source_is_selected(SourceId(0)));
        assert_eq!(current.get(SourceId(0)), original.get(SourceId(0)));
        let mut unowned = SourceMap::default();
        unowned.add(PathBuf::from("main.omg"), String::from("data Item {}"));
        assert!(unowned.fork_source_selection().is_err());
    }

