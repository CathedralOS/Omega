use std::path::PathBuf;
use std::sync::Arc;

use crate::{SourceId, SourceSpan, Span};
use semantic_vocabulary::PackageKeyIdentity;

#[derive(Debug, Clone, Copy, Default, PartialEq, Eq, compiler_storage::Record)]
pub enum SourceOrigin {
    #[default]
    User,
    Toolchain,
}

/// Visibility stratum for source-level name resolution.
///
/// This is deliberately independent of [`SourceOrigin`]. A source generated
/// by a build activation is still user/package provenance, but its
/// declarations must not become candidates for references authored in the
/// same package before that activation ran
/// (wiki/spec/build/execution.md, "Generated-source boundary").
///
/// The rule is per package, so a consumer sees the generated declarations
/// handed off by its dependencies while each dependency's own authored
/// units still cannot select them: the same package compiles once as the
/// review root, where its generated units are the current activation's
/// extension, and again inside every consumer, where they arrive through a
/// bundle. Both routes must reach the same resolution verdict.
#[derive(Debug, Clone, Copy, Default, PartialEq, Eq, compiler_storage::Record)]
pub enum SourceResolutionStratum {
    #[default]
    Base,
    /// Generated by the activation this compilation itself admitted.
    CurrentActivationExtension,
    /// Generated by a dependency's already-reviewed activation and joined
    /// through its generated-source bundle. Assembled with the base, so it
    /// keeps base namespace and import behavior, but invisible to authored
    /// units of its own package.
    DependencyActivationExtension,
}

/// Which dependency context one checked source instance belongs to.
///
/// Identical bytes may join a compilation once per scope: a source selected
/// by both dependency purposes carries two checked instances that share no
/// module namespace, target-scoped declaration selection, or declaration
/// authority (wiki/spec/build/scoped_execution.md, "Two checked contexts").
/// This is deliberately independent of [`SourceResolutionStratum`], which is
/// an activation-visibility boundary, not a dependency context.
#[derive(
    Debug, Clone, Copy, Default, PartialEq, Eq, PartialOrd, Ord, Hash, compiler_storage::Record,
)]
pub enum DependencyScope {
    #[default]
    Product,
    Build,
}

#[derive(Debug, Clone, PartialEq, Eq, compiler_storage::Record)]
pub struct SourceFile {
    pub source_id: SourceId,
    pub path: PathBuf,
    /// Canonical package directory selected by the frontend. Source files are
    /// package members by location, so ownership must not be inferred from a
    /// declaration spelling later in the pipeline.
    pub package_root: PathBuf,
    /// Stable package identity supplied by a reconciled package graph. Paths
    /// remain source-loading locations and diagnostic context; they are not
    /// nominal identity. Transitional, toolchain, and standalone sources may
    /// not have an admitted package identity yet.
    pub package_identity: Option<PackageKeyIdentity>,
    /// The dependency context this instance was checked under. Two instances
    /// of one path carry the same package identity and differ only here.
    pub dependency_scope: DependencyScope,
    pub origin: SourceOrigin,
    pub resolution_stratum: SourceResolutionStratum,
    pub source: Arc<str>,
}

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct SourcePosition {
    pub line: usize,
    pub column: usize,
}

impl SourceFile {
    pub fn source_span(&self, span: Span) -> SourceSpan {
        SourceSpan::new(self.source_id, span)
    }

    pub fn text_at(&self, span: Span) -> &str {
        self.source.get(span.start..span.end).unwrap_or("")
    }
}

impl SourcePosition {
    pub fn of(source: &str, byte_offset: usize) -> Self {
        let mut line = 1;
        let mut column = 1;

        for (index, character) in source.char_indices() {
            if index >= byte_offset {
                break;
            }

            if character == '\n' {
                line += 1;
                column = 1;
            } else {
                column += 1;
            }
        }

        SourcePosition { line, column }
    }
}

#[cfg(test)]
mod tests {
    use std::path::PathBuf;
    use std::sync::Arc;

    use crate::{
        DependencyScope, SourceFile, SourceId, SourceOrigin, SourceResolutionStratum, Span,
    };

    #[test]
    fn source_span_carries_source_identity() {
        let file = SourceFile {
            source_id: SourceId(7),
            path: PathBuf::from("main.omg"),
            package_root: PathBuf::from("."),
            package_identity: None,
            dependency_scope: DependencyScope::Product,
            origin: SourceOrigin::User,
            resolution_stratum: SourceResolutionStratum::Base,
            source: Arc::from("machine main {}"),
        };
        let span = file.source_span(Span::new(8, 12));

        assert_eq!(span.source_id, SourceId(7));
        assert_eq!(file.text_at(span.span), "main");
    }
}
