#!/usr/bin/env sh
# Canonical repository paths for the bootstrap chain.
#
# This file is replaceable invocation plumbing. It names source owners only;
# it does not perform a translation or contribute semantics to a compiler edge.

if [ -z "${OMEGA_REPO_ROOT:-}" ] || [ ! -f "$OMEGA_REPO_ROOT/TASKS_BOOTSTRAP.md" ]; then
  echo "bootstrap paths: OMEGA_REPO_ROOT is not an Omega repository root" >&2
  return 2
fi

OMEGA_PATH_BOOTSTRAP=$OMEGA_REPO_ROOT/bootstrap

OMEGA_PATH_ALPHA=$OMEGA_PATH_BOOTSTRAP/alpha

OMEGA_PATH_BETA=$OMEGA_PATH_BOOTSTRAP/beta
OMEGA_PATH_BETA_COMPILER=$OMEGA_PATH_BETA/compiler
OMEGA_PATH_BETA_COMPILER_SOURCE=$OMEGA_PATH_BETA_COMPILER/beta_compiler.beta
OMEGA_PATH_BETA_COMPILER_TAPE=$OMEGA_PATH_BETA_COMPILER/beta_compiler_bytecode.tape

OMEGA_PATH_GAMMA=$OMEGA_PATH_BOOTSTRAP/gamma
OMEGA_PATH_GAMMA_EVALUATOR=$OMEGA_PATH_GAMMA/evaluator
OMEGA_PATH_GAMMA_EVALUATOR_SOURCE=$OMEGA_PATH_GAMMA_EVALUATOR/gamma_evaluator.beta
OMEGA_PATH_GAMMA_EVALUATOR_TAPE=$OMEGA_PATH_GAMMA_EVALUATOR/gamma_evaluator_bytecode.tape

OMEGA_PATH_CONCATENATIVE_GAMMA=$OMEGA_PATH_GAMMA/bootstrap/concatenative
OMEGA_PATH_CONCATENATIVE_GAMMA_EVALUATOR=$OMEGA_PATH_CONCATENATIVE_GAMMA/evaluator
OMEGA_PATH_CONCATENATIVE_GAMMA_EVALUATOR_SOURCE=$OMEGA_PATH_CONCATENATIVE_GAMMA_EVALUATOR/gamma_evaluator.beta
OMEGA_PATH_CONCATENATIVE_GAMMA_COMPILER=$OMEGA_PATH_CONCATENATIVE_GAMMA/compiler
OMEGA_PATH_CONCATENATIVE_GAMMA_COMPILER_SOURCE=$OMEGA_PATH_CONCATENATIVE_GAMMA_COMPILER/gamma_compiler.gamma
OMEGA_PATH_CONCATENATIVE_GAMMA_COMPILER_RECEIPT=$OMEGA_PATH_CONCATENATIVE_GAMMA_COMPILER/gamma_compiler.beta
OMEGA_PATH_CONCATENATIVE_GAMMA_COMPILER_TAPE=$OMEGA_PATH_CONCATENATIVE_GAMMA_COMPILER/gamma_compiler_bytecode.tape

OMEGA_PATH_DELTA=$OMEGA_PATH_BOOTSTRAP/delta
OMEGA_PATH_DELTA_COMPILER=$OMEGA_PATH_DELTA/compiler
OMEGA_PATH_DELTA_COMPILER_SOURCE=$OMEGA_PATH_DELTA_COMPILER/delta_compiler.gamma
OMEGA_PATH_DELTA_COMPILER_COMPOSED=$OMEGA_PATH_DELTA_COMPILER/delta_compiler.composed
OMEGA_PATH_CONCATENATIVE_DELTA_COMPILER=$OMEGA_PATH_DELTA/bootstrap/concatenative-compiler
OMEGA_PATH_CONCATENATIVE_DELTA_COMPILER_SOURCE=$OMEGA_PATH_CONCATENATIVE_DELTA_COMPILER/delta_compiler.gamma

OMEGA_PATH_EPSILON=$OMEGA_PATH_BOOTSTRAP/epsilon
OMEGA_PATH_EPSILON_COMPILER=$OMEGA_PATH_EPSILON/compiler
OMEGA_PATH_EPSILON_COMPILER_SOURCE=$OMEGA_PATH_EPSILON_COMPILER/epsilon_compiler.delta
OMEGA_PATH_EPSILON_COMPILER_TAPE=$OMEGA_PATH_EPSILON_COMPILER/epsilon_compiler_bytecode.tape

OMEGA_PATH_OMEGA=$OMEGA_REPO_ROOT/source/omega
OMEGA_PATH_OMEGA_D=$OMEGA_PATH_BOOTSTRAP/omega
OMEGA_PATH_OMEGA_COMPILER=$OMEGA_PATH_OMEGA_D/compiler
OMEGA_PATH_OMEGA_COMPILER_SOURCES=$OMEGA_PATH_OMEGA_D/omega_compiler.epsilon.sources

export OMEGA_REPO_ROOT OMEGA_PATH_BOOTSTRAP OMEGA_PATH_ALPHA
export OMEGA_PATH_BETA OMEGA_PATH_BETA_COMPILER
export OMEGA_PATH_BETA_COMPILER_SOURCE OMEGA_PATH_BETA_COMPILER_TAPE
export OMEGA_PATH_GAMMA OMEGA_PATH_GAMMA_EVALUATOR
export OMEGA_PATH_GAMMA_EVALUATOR_SOURCE OMEGA_PATH_GAMMA_EVALUATOR_TAPE
export OMEGA_PATH_CONCATENATIVE_GAMMA OMEGA_PATH_CONCATENATIVE_GAMMA_EVALUATOR
export OMEGA_PATH_CONCATENATIVE_GAMMA_EVALUATOR_SOURCE
export OMEGA_PATH_CONCATENATIVE_GAMMA_COMPILER
export OMEGA_PATH_CONCATENATIVE_GAMMA_COMPILER_SOURCE
export OMEGA_PATH_CONCATENATIVE_GAMMA_COMPILER_RECEIPT
export OMEGA_PATH_CONCATENATIVE_GAMMA_COMPILER_TAPE
export OMEGA_PATH_DELTA OMEGA_PATH_DELTA_COMPILER OMEGA_PATH_DELTA_COMPILER_SOURCE
export OMEGA_PATH_DELTA_COMPILER_COMPOSED
export OMEGA_PATH_CONCATENATIVE_DELTA_COMPILER
export OMEGA_PATH_CONCATENATIVE_DELTA_COMPILER_SOURCE
export OMEGA_PATH_EPSILON OMEGA_PATH_EPSILON_COMPILER
export OMEGA_PATH_EPSILON_COMPILER_SOURCE OMEGA_PATH_EPSILON_COMPILER_TAPE
export OMEGA_PATH_OMEGA OMEGA_PATH_OMEGA_D OMEGA_PATH_OMEGA_COMPILER
export OMEGA_PATH_OMEGA_COMPILER_SOURCES
